/************************************************************
 * 文件名: dac_app.c
 * 功能:   DAC 应用层实现 (电压 -> 12位DAC值)
 * 平台:   2026 CIMC GD32F4xx
 ************************************************************/
#include "dac_app.h"

#define DAC_VREF        3.3f       /* 参考电压 (按实际硬件调整) */
#define DAC_FULL_SCALE  4095.0f    /* 12位满量程 */

/************************************************************
 * 函数: dac_app_set_voltage
 * 描述: 设置 DAC 输出电压 (自动钳位到 0~Vref)
 * 参数: volt - 目标电压 (V)
 ************************************************************/
void dac_app_set_voltage(float volt)
{
    int32_t raw;

    if (volt < 0.0f) {
        volt = 0.0f;
    }
    if (volt > DAC_VREF) {
        volt = DAC_VREF;
    }
    raw = (int32_t)(volt / DAC_VREF * DAC_FULL_SCALE + 0.5f);
    dac_set_raw((uint16_t)raw);
}
/************************************************************
 * 函数: dac_app_set_raw
 * 描述: 直接设置 DAC 12位原始值 (0~4095, 超出钳位)
 * 参数: raw - 12位DAC原始值
 ************************************************************/
void dac_app_set_raw(uint16_t raw)
{
    if (raw > 4095U) {
        raw = 4095U;            /* 钳位到12位满量程 */
    }
    dac_set_raw(raw);
}
